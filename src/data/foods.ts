const DIETS: Record<string, Diet> = { vg: 'vegan', v: 'veg', e: 'egg', n: 'nonveg' }

export const slug = (s: string) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')

function parseUnits(spec: string, liquid: boolean): Unit[] {
  const units: Unit[] = spec.split(',').map((tok) => {
    const eq = tok.lastIndexOf('=')
    const label = (eq === -1 ? tok : tok.slice(0, eq)).trim()
    const g = eq === -1 ? PRESETS[label] : Number(tok.slice(eq + 1))
    return { key: slug(label), label, g }
  })
  units.push(liquid ? { key: 'ml', label: 'ml', g: 1 } : { key: 'g', label: 'g', g: 1 })
  return units
}

